#!/usr/bin/env node
/**
 * @fileoverview Generate one MDX story per token module page in
 * `src/data/storybook.json`, so the sidebar is tied to the data instead of
 * hand-maintained.
 *
 * Storybook builds its sidebar from a STATIC story index, so each token page
 * needs a real story file. Every item whose `table` is `tokenModule` gets one,
 * titled by its path in the tree (`Tokens/Fonts/lineHeight`) — folders, order,
 * and titles all come from the tree (`src/data/tree.ts`, run with Node's type
 * stripping), so nothing here lists groups or folders.
 *
 * Component tokens are not generated: each component's token table lives on its
 * hand-authored `stories/Components/{Name}/Tokens.mdx` page, below Docs.
 *
 * Output goes to the gitignored `generated/` subfolder, fully owned + rebuilt
 * each run. Wired into `prestorybook` / `prebuild`.
 *
 * @module scripts/generate-token-stories
 */

import fs from "fs"
import path from "path"
import { fileURLToPath } from "url"
import { buildTree, flatten } from "../src/data/tree.ts"

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const sbRoot = path.resolve(__dirname, "..")

const MARKER = "{/* GENERATED by scripts/generate-token-stories.mjs — do not edit; regenerated on each storybook build. */}"

const data = JSON.parse(fs.readFileSync(path.resolve(sbRoot, "src/data/storybook.json"), "utf8"))
const pages = flatten(buildTree(data.items, data.defaults ?? {})).filter(
  (item) => !item.isFolder && item.settings.table === "tokenModule"
)

// Fully owned output dir: wipe + recreate, so a removed page disappears.
const out = path.resolve(sbRoot, "stories/Tokens/generated")
fs.rmSync(out, { recursive: true, force: true })
fs.mkdirSync(out, { recursive: true })

for (const page of pages) {
  fs.writeFileSync(
    path.join(out, `${page.name}.mdx`),
    `import { Meta } from "@storybook/addon-docs/blocks"
import { TokenStory } from "../TokenStory"

<Meta title="${page.title}" />

${MARKER}

<TokenStory id="${page.id}" />
`
  )
}

console.log(`✓ token stories generated: ${pages.length} module`)
