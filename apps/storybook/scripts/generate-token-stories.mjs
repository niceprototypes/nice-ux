#!/usr/bin/env node
/**
 * @fileoverview Generate the per-entry MDX token stories for Tokens/Components
 * and Tokens/Modules, so the sidebar folder list is tied to the token data
 * instead of hand-maintained.
 *
 * The two "Docs" pages (Tokens/Components, Tokens/Modules) already render the
 * true list dynamically (componentPrefixesWithTokens / tokenTables). But
 * Storybook builds its sidebar from a STATIC story index, so each per-entry
 * sub-page needs a real story file. This script writes those files from the
 * same sources the Docs pages use:
 *
 *   - Components: nice-styles `src/tokens/components/*.json` stems
 *     (= componentPrefixesWithTokens = Object.keys(componentTokensData)).
 *   - Modules:    `stories/Tokens/Modules/tables/*.tsx` stems (the tokenTables
 *     config), minus the color family — those share the bespoke Colors.mdx.
 *
 * Output goes to gitignored `generated/` subfolders, fully owned + rebuilt each
 * run (add/remove a token file → the sidebar matches on the next build). Wired
 * into `prestorybook` / `prebuild`.
 *
 * @module scripts/generate-token-stories
 */

import fs from "fs"
import path from "path"
import { fileURLToPath } from "url"

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const sbRoot = path.resolve(__dirname, "..")

// The four color modules collapse onto the hand-authored Colors.mdx.
const COLOR_FAMILY = new Set(["color", "backgroundColor", "borderColor", "brandColor"])

const MARKER = "{/* GENERATED by scripts/generate-token-stories.mjs — do not edit; regenerated on each storybook build. */}"

const cap = (s) => s.charAt(0).toUpperCase() + s.slice(1)

/** Stems of files with `ext` in `dir`, minus `exclude`. */
function stems(dir, ext, exclude = new Set()) {
  if (!fs.existsSync(dir)) throw new Error(`generate-token-stories: source dir not found: ${dir}`)
  return fs
    .readdirSync(dir)
    .filter((f) => f.endsWith(ext))
    .map((f) => f.slice(0, -ext.length))
    .filter((s) => !exclude.has(s))
    .sort()
}

/** Wipe + recreate a fully-owned output dir. */
function fresh(dir) {
  fs.rmSync(dir, { recursive: true, force: true })
  fs.mkdirSync(dir, { recursive: true })
  return dir
}

// ── Components ──────────────────────────────────────────────────────────────
const componentPrefixes = stems(path.resolve(sbRoot, "../styles/src/tokens/components"), ".json")
const componentsOut = fresh(path.resolve(sbRoot, "stories/Tokens/Components/generated"))

for (const prefix of componentPrefixes) {
  const Name = cap(prefix)
  fs.writeFileSync(
    path.join(componentsOut, `${Name}.mdx`),
    `import { Meta } from "@storybook/addon-docs/blocks"
import { StoryHeader } from "../../../../src/components/Story"
import { ComponentTokenTable } from "../../../../src/dataTables/components/tokens/Components"

<Meta title="Tokens/Components/${Name}" />

${MARKER}

<style>{\`.sbdocs.sbdocs-content { max-width: 100%; }\`}</style>

<StoryHeader
  title="${Name}"
  description="Component-level tokens for ${Name} — which are initialized to core tokens and which are literal string values."
/>

<ComponentTokenTable prefix="${prefix}" />
`
  )
}

// ── Modules (non-color; color family lives on Colors.mdx) ────────────────────
const moduleGroups = stems(path.resolve(sbRoot, "stories/Tokens/Modules/tables"), ".tsx", new Set(["index", ...COLOR_FAMILY]))
const modulesOut = fresh(path.resolve(sbRoot, "stories/Tokens/Modules/generated"))

for (const group of moduleGroups) {
  fs.writeFileSync(
    path.join(modulesOut, `${group}.mdx`),
    `import { Meta } from "@storybook/addon-docs/blocks"
import { TokenStory } from "../TokenStory"

<Meta title="Tokens/Modules/${group}" />

${MARKER}

<TokenStory name="${group}" />
`
  )
}

console.log(`✓ token stories generated: ${componentPrefixes.length} component (${componentPrefixes.join(", ")}), ${moduleGroups.length} module`)
