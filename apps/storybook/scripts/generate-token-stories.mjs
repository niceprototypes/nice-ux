#!/usr/bin/env node
/**
 * @fileoverview Generate the per-entry MDX token stories for Tokens, so
 * the sidebar folder list is tied to the token data instead of hand-maintained.
 *
 * The Tokens "Docs" page already renders the true list dynamically
 * (tokenTables). But Storybook builds its sidebar from a STATIC story index, so
 * each per-entry sub-page needs a real story file. This script writes those
 * files from `stories/Tokens/tables/*.tsx` stems (the tokenTables
 * config), minus the color family — those share the bespoke Colors.mdx.
 *
 * Component tokens are not generated: each component's token table lives on its
 * hand-authored `stories/React/Components/{Name}/Tokens.mdx` page, below Docs.
 *
 * Output goes to the gitignored `generated/` subfolder, fully owned + rebuilt
 * each run (add/remove a table → the sidebar matches on the next build). Wired
 * into `prestorybook` / `prebuild`.
 *
 * @module scripts/generate-token-stories
 */

import fs from "fs"
import path from "path"
import { fileURLToPath } from "url"

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const sbRoot = path.resolve(__dirname, "..")

// The four color modules collapse onto the hand-authored Colors.mdx.
const COLOR_FAMILY = new Set(["color", "backgroundColor", "borderColor", "brandColor"])

const MARKER = "{/* GENERATED by scripts/generate-token-stories.mjs — do not edit; regenerated on each storybook build. */}"

/** Stems of files with `ext` in `dir`, minus `exclude`. */
function stems(dir, ext, exclude = new Set()) {
  if (!fs.existsSync(dir)) throw new Error(`generate-token-stories: source dir not found: ${dir}`)
  return fs
    .readdirSync(dir)
    .filter((f) => f.endsWith(ext))
    .map((f) => f.slice(0, -ext.length))
    .filter((s) => !exclude.has(s))
    .sort()
}

/** Wipe + recreate a fully-owned output dir. */
function fresh(dir) {
  fs.rmSync(dir, { recursive: true, force: true })
  fs.mkdirSync(dir, { recursive: true })
  return dir
}

// ── Modules (non-color; color family lives on Colors.mdx) ────────────────────
const moduleGroups = stems(path.resolve(sbRoot, "stories/Tokens/tables"), ".tsx", new Set(["index", ...COLOR_FAMILY]))
const modulesOut = fresh(path.resolve(sbRoot, "stories/Tokens/generated"))

for (const group of moduleGroups) {
  fs.writeFileSync(
    path.join(modulesOut, `${group}.mdx`),
    `import { Meta } from "@storybook/addon-docs/blocks"
import { TokenStory } from "../TokenStory"

<Meta title="Tokens/${group}" />

${MARKER}

<TokenStory name="${group}" />
`
  )
}

console.log(`✓ token stories generated: ${moduleGroups.length} module`)
